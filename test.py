# [종합실습] 머신러닝 기반 예측 모델 웹 서비스 구축 + 발표( 화면 시연 / 모델링만 코드 전체리뷰)
# 1. 실습 개요
# - 목표: 머신러닝 예측 파이프라인을 구축하고, 최적화된 모델을 저장 한 뒤, FastAPI 백엔드 및 웹 프론트엔드와 연동하여 실시간 예측 및 모델 성능 지표를 제공하는 AI 웹 서비스를 구현합니다.
# - 진행 방식: 자유 주제 선정

# 2. 핵심 요구사항 (필수 구현 사항)
# [1] 데이터셋 조건
#   * 최소 1,000행(Row) 이상의 정형 데이터셋 확보 및 활용(Kaggle, AI 허브, 공공데이터포털 등 활용)
# [2] 모델링 및 하이퍼파라미터 튜닝
#   * 알고리즘 선택 (택 1):
#     - 회귀(Regression): LinearRegression, Ridge, Lasso 중 선택 또는 비교
#     - 분류(Classification): LogisticRegression (이진 분류 또는 다중 분류)
#   * 파이프라인 구축: sklearn.pipeline.Pipeline (및 필요시 ColumnTransformer)을 사용하여 전처리 과정과 모델 학습 과정을 단일 파이프라인으로 통합
#   * 교차 검증 및 최적화: GridSearchCV를 활용하여 최적의 하이퍼파라미터를 탐색하고, 최적 모델(best_estimator_) 도출

# [3] 모델 영속화 (저장 및 로드)
#   * 학습이 완료된 최종 파이프라인 모델과 검증 데이터셋 기준의 성능 평가 지표는 joblib을 사용하여 파일(.pkl )로 저장
#   * 웹 서버(FastAPI) 구동 후 예측 요청이 들어올 때마다 모델을 재학습하지 않고, 저장된 모델 파일을 로드하여 추론만 수행

# [4] 백엔드 API 서버 (Python / FastAPI)
#   * 클라이언트로부터 예측에 필요한 피처 값들을 형태로 입력받는 엔드포인트 구현
#   * 입력받은 데이터를 모델 입력 규격에 맞게 변환한 뒤 예측 수행
#   * 필수 반환 데이터:
#     (1) 예측 결과값 (회귀: 예측 수치 / 분류: 예측 클래스 및 확률)
#     (2) 모델 성능 평가 지표 (회귀 모델: 결정계수 R2 Score / 분류 모델: F1-Score)

# [5] 프론트엔드 웹 UI (HTML / CSS / JS)  AI 로 적극 활용
#   * 사용자가 예측에 필요한 변수들을 직관적으로 입력할 수 있는 폼(Form) 화면 구성
#   * axios를 이용한 비동기 통신으로 FastAPI 서버에 데이터를 전송하고,
#     반환받은 예측 결과와 모델 성능 지표(R2 또는 F1-Score)를 화면에 동적으로 렌더링
